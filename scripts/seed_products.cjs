async function seed() {
  const targetEmail = 'shubhamvmore12@gmail.com';
  console.log(`Starting product seeding for ${targetEmail}...`);

  try {
    const [users] = await pool.query('SELECT uid, email, shopId FROM users WHERE LOWER(email) = ?', [targetEmail]);
    if (!users || users.length === 0) {
      console.error(`User ${targetEmail} not found in database!`);
      process.exit(1);
    }

    const shopId = users[0].shopId;
    console.log(`Found shop ID: ${shopId}`);

    console.log(`Total products to insert: ${products.length}`);

    let inserted = 0;
    let skipped = 0;

    for (const p of products) {
      const id = crypto.randomUUID();
      const barcodeVal = p.barcode ? p.barcode.trim() : null;
      const shortCodeVal = p.shortCode ? p.shortCode.trim() : null;

      try {
        await pool.query(
          `INSERT INTO products 
           (id, shopId, name, category, brand, unit, purchasePrice, sellingPrice, mrp, gst, stock, minStock, sku, barcode, shortCode, isLoose, createdAt) 
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [
            id,
            shopId,
            p.name,
            p.category,
            p.brand,
            p.unit,
            p.purchasePrice,
            p.sellingPrice,
            p.mrp,
            p.gst,
            p.stock,
            p.minStock,
            p.sku,
            barcodeVal,
            shortCodeVal,
            p.isLoose ? 1 : 0,
            new Date().toISOString()
          ]
        );
        inserted++;
      } catch (err) {
        console.warn(`Error inserting product "${p.name}":`, err.message);
        skipped++;
      }
    }

    console.log(`✅ Seeding Complete!`);
    console.log(`Inserted: ${inserted}`);
    console.log(`Skipped/Failed: ${skipped}`);

    const [countResult] = await pool.query('SELECT COUNT(*) as total FROM products WHERE shopId = ?', [shopId]);
    console.log(`Total products now in shop ${shopId}: ${countResult[0].total}`);

    process.exit(0);
  } catch (error) {
    console.error('Fatal error during seeding:', error);
    process.exit(1);
  }
}

